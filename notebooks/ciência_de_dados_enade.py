def extrair_dados_ufop(df, ano):
    if df.empty:
        return pd.DataFrame()

    # 1. Localizar a linha da UFOP procurando por 'OURO PRETO' em todas as colunas de texto
    mascara_ufop = pd.Series(False, index=df.index)
    for c in df.columns:
        mascara_ufop = mascara_ufop | df[c].astype(str).str.upper().str.contains("OURO PRETO", na=False)

    df_ufop = df[mascara_ufop].copy()
    if df_ufop.empty:
        return pd.DataFrame()

    dados = {"Ano": ano}

    # 2. Resgatar as métricas principais de forma flexível
    for c in df_ufop.columns:
        col_upper = str(c).upper()
        if "CPC" in col_upper and "CONT" in col_upper:
            dados["CPC (Contínuo)"] = pd.to_numeric(df_ufop[c].values[0], errors="coerce")
        elif "CPC" in col_upper and "FAIXA" in col_upper:
            dados["CPC (Faixa)"] = df_ufop[c].values[0]
        elif "PADRONIZADA" in col_upper and "IDD" in col_upper:
            dados["Nota Padronizada - IDD"] = pd.to_numeric(df_ufop[c].values[0], errors="coerce")
        elif "ENADE" in col_upper and "CONT" in col_upper:
            dados["Conceito Enade (Contínuo)"] = pd.to_numeric(df_ufop[c].values[0], errors="coerce")
        elif "BRUTA" in col_upper and "CE" in col_upper:
            dados["Nota Bruta - CE"] = pd.to_numeric(df_ufop[c].values[0], errors="coerce")

    return pd.DataFrame([dados])

