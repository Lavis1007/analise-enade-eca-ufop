def achar_coluna(df, palavras_obrigatorias, palavras_proibidas=[]):
    for col in df.columns:
        c_upper = str(col).upper()
        if all(p in c_upper for p in palavras_obrigatorias):
            if not any(p in c_upper for p in palavras_proibidas):
                return col
    return None

dados_corrigidos = []

for ano, df_ano in bases_ano.items():
    if df_ano.empty:
        continue

    # Linha da UFOP
    mascara_ufop = pd.Series(False, index=df_ano.index)
    for c in df_ano.columns:
        mascara_ufop = mascara_ufop | df_ano[c].astype(str).str.upper().str.contains("OURO PRETO", na=False)

    linha_ufop = df_ano[mascara_ufop]
    if linha_ufop.empty:
        continue

    # Mapeamento flexível por palavras-chave
    col_cpc = achar_coluna(df_ano, ["CPC", "CONT"])
    col_ce = achar_coluna(df_ano, ["PADRONIZADA", "ESPEC"], ["GERAL"]) or achar_coluna(df_ano, ["PADRONIZADA", "CE"])
    col_idd = achar_coluna(df_ano, ["PADRONIZADA", "IDD"]) or achar_coluna(df_ano, ["IDD", "CONT"])
    col_didat = achar_coluna(df_ano, ["DIDAT"], ["BRUT"]) or achar_coluna(df_ano, ["ORGANIZA"], ["BRUT"])
    col_infra = achar_coluna(df_ano, ["INFRA"], ["BRUT"])
    col_amplia = achar_coluna(df_ano, ["AMPLIA"], ["BRUT"]) or achar_coluna(df_ano, ["OPORTUN"], ["BRUT"])
    col_mest = achar_coluna(df_ano, ["MEST"], ["BRUT"])
    col_dout = achar_coluna(df_ano, ["DOUT"], ["BRUT"])
    col_regime = achar_coluna(df_ano, ["REGIME"], ["BRUT"]) or achar_coluna(df_ano, ["TRABALHO"], ["BRUT"])

    def extrair_val(col):
        if col:
            v = pd.to_numeric(linha_ufop[col].values[0], errors="coerce")
            # Se a nota docente estiver em proporção (0 a 1), converte para a escala 0 a 5
            if pd.notnull(v) and v <= 1.0 and ("MEST" in col.upper() or "DOUT" in col.upper() or "REGIME" in col.upper()):
                return v * 5.0
            return v
        return np.nan

    dados_corrigidos.append({
        "Ano": ano,
        "CPC (Contínuo)": extrair_val(col_cpc),
        "Nota Padronizada - CE": extrair_val(col_ce),
        "Nota Padronizada - IDD": extrair_val(col_idd),
        "Nota Padronizada - Didático-Pedagógica": extrair_val(col_didat),
        "Nota Padronizada - Infraestrutura": extrair_val(col_infra),
        "Nota Padronizada - Ampliação da Formação": extrair_val(col_amplia),
        "Nota Padronizada - Mestres": extrair_val(col_mest),
        "Nota Padronizada - Doutores": extrair_val(col_dout),
        "Nota Padronizada - Regime de Trabalho": extrair_val(col_regime),
    })

insumos_ufop = pd.DataFrame(dados_corrigidos).sort_values("Ano").reset_index(drop=True)
