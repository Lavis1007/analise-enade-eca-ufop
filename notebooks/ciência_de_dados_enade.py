def filtrar_forca_bruta(df):
    if df.empty: return df

    # 1. FILTRO DE CURSO (BUSCA EM TODAS AS COLUNAS)
    mascara_curso = pd.Series(False, index=df.index)
    for c in df.columns:
        valores = df[c].astype(str).str.upper()
        # Procura pelo nome ou pelo código oficial do MEC/INEP para o curso (5814)
        mascara_curso = mascara_curso | valores.str.contains('CONTROLE E AUTOMA', na=False) | (valores == '5814')

    if not mascara_curso.any():
        return pd.DataFrame(columns=df.columns) # Retorna vazio se não achar o curso

    # Aplica o filtro de curso
    df = df[mascara_curso].copy()

    # 2. FILTRO DE ESTADO (SUDESTE)
    mascara_uf = pd.Series(False, index=df.index)
    for c in df.columns:
        # Foca nas colunas que parecem ser de localização
        if any(palavra in str(c).upper() for palavra in ['UF', 'ESTADO', 'SIGLA']):
            valores_uf = df[c].astype(str).str.strip().str.upper()
            mascara_uf = mascara_uf | valores_uf.isin(ESTADOS_SUDESTE)

    if not mascara_uf.any():
        return pd.DataFrame(columns=df.columns)

    return df[mascara_uf].copy()

