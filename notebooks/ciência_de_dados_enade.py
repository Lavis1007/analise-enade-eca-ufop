def adicionar_regiao(df):
    """
    Procura a coluna de Estado (UF) e cria uma nova coluna chamada 'Região'
    baseada no dicionário REGIAO.
    """
    if df.empty: return df

    col_uf = None
    for c in df.columns:
        if str(c).strip().upper() in ['SIGLA DA UF', 'SG_UF', 'UF', 'SIGLA UF', 'UF_IES']:
            col_uf = c
            break

    if col_uf:
        # Cria a nova coluna 'Região' mapeando a sigla do estado
        df['Região'] = df[col_uf].map(REGIAO)

    return df

