def extrair_desempenho_ufop(caminho_excel, ano):
    """Lê a planilha do ano correspondente, busca a linha da UFOP para

    Engenharia de Controle e Automação e extrai os indicadores principais.
    """
    # Lê a primeira aba da planilha
    df = pd.read_excel(caminho_excel, sheet_name=0)

    # Limpa espaços invisíveis nos nomes das colunas
    df.columns = df.columns.str.strip()

    # 1. Filtro do Curso: Procura por 'CONTROLE E AUTOMA' ou pelo código do curso (5814)
    mascara_curso = pd.Series(False, index=df.index)
    for col in df.columns:
        vals = df[col].astype(str).str.upper()
        mascara_curso = (
            mascara_curso
            | vals.str.contains("CONTROLE E AUTOMA", na=False)
            | (vals == "5814")
        )

    # 2. Filtro da Instituição: Procura por 'OURO PRETO'
    mascara_ufop = pd.Series(False, index=df.index)
    for col in df.columns:
        mascara_ufop = mascara_ufop | df[col].astype(
            str
        ).str.upper().str.contains("OURO PRETO", na=False)

    # Aplica os dois filtros combinados
    df_filtrado = df[mascara_curso & mascara_ufop].copy()

    if df_filtrado.empty:
        return pd.DataFrame()

    # Dicionário para armazenar as métricas capturadas
    dados = {"Ano": ano}

    # Varre as colunas dinamicamente para extrair os indicadores
    for col in df_filtrado.columns:
        col_up = str(col).upper()

        if "CPC" in col_up and "CONT" in col_up:
            dados["CPC (Contínuo)"] = pd.to_numeric(
                df_filtrado[col].values[0], errors="coerce"
            )
        elif "CPC" in col_up and "FAIXA" in col_up:
            dados["CPC (Faixa)"] = df_filtrado[col].values[0]
        elif "ENADE" in col_up and "CONT" in col_up:
            dados["Conceito ENADE (Contínuo)"] = pd.to_numeric(
                df_filtrado[col].values[0], errors="coerce"
            )
        elif "PADRONIZADA" in col_up and "IDD" in col_up:
            dados["Nota Padronizada - IDD"] = pd.to_numeric(
                df_filtrado[col].values[0], errors="coerce"
            )
        elif "BRUTA" in col_up and "CE" in col_up:
            dados["Nota Bruta - CE"] = pd.to_numeric(
                df_filtrado[col].values[0], errors="coerce"
            )

    return pd.DataFrame([dados])


