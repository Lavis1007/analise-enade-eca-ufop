def achar_coluna(df, palavras_obrigatorias, palavras_proibidas=[]):
    """Auxiliar para encontrar colunas com variação de nome nos arquivos do INEP."""
    if df.empty:
        return None
    for col in df.columns:
        c_up = str(col).upper()
        if all(p in c_up for p in palavras_obrigatorias):
            if not any(p in c_up for p in palavras_proibidas):
                return col
    return None


